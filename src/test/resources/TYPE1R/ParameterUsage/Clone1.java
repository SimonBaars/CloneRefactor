public class Clone1 {
	public void method1(int x, String name) {
		int doubled = x * 2;
		int tripled = x * 3;
		System.out.println(name + " doubled: " + doubled);
		System.out.println(name + " tripled: " + tripled);
		System.out.println("Original: " + x);
		System.out.println("Name: " + name);
	}
}
